// Writes src/lib/upcoming.ts: the terrain sunrise/sunset times (2 m mast) of the south-polar
// sites, so the dashboard can open on a site whose next event is close (a countdown that moves)
// without downloading every site file first.
//   npm run gen-upcoming   (also runs at the end of npm run sync-data)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sites = join(here, "..", "public", "data", "sites");
const index = JSON.parse(readFileSync(join(sites, "index.json"), "utf8"));
const out = {};
for (const h of index.sites) {
  if (h.group !== "polar" && h.group !== "artemis") continue;
  const s = JSON.parse(readFileSync(join(sites, `${h.id}.json`), "utf8"));
  const evs = s.events[String(s.default_mast_m)] ?? [];
  // epoch minutes; negative = sunset, positive = sunrise
  out[h.id] = evs
    .filter((e) => e.target === "sun" && (e.kind === "first_light" || e.kind === "last_light"))
    .map((e) => Math.round(Date.parse(/Z$/i.test(e.utc) ? e.utc : e.utc + "Z") / 60000) * (e.kind === "last_light" ? -1 : 1));
}
const text = `// Generated by scripts/gen-upcoming.mjs from public/data/sites. Do not edit by hand.
// Per south-polar site: terrain sunrise (+) and sunset (-) times at the default mast, in epoch minutes.
export const UPCOMING: Record<string, number[]> = ${JSON.stringify(out)};
`;
writeFileSync(join(here, "..", "src", "lib", "upcoming.ts"), text);
console.log(`upcoming.ts: ${Object.keys(out).length} sites`);
